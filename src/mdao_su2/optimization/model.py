def add_objective_comp(group, compiled):
    """Add ``obj_comb`` from a compiled expression and connect its inputs."""
    group.add_subsystem('obj_comb', ObjectiveComp(compiled))
    for source, target in compiled.connections:
        group.connect(source, target)


def add_linear_comps(group, linear_compiled):
    """Add one ``ExecComp`` per ``[[constraints.linear]]`` and connect its
    inputs from the point outputs."""
    for constraint, compiled in linear_compiled:
        group.add_subsystem(constraint.component, om.ExecComp(compiled.execcomp_src))
        for source, target in compiled.connections:
            group.connect(source, target)


def responses(cfg, scenario_prefix, geometry_name, geometry_constraints):
    """The driver's objective and constraints as ``(path, kind, kwargs)``.

    ``kind`` is ``objective``, ``lift``, ``moment``, ``linear`` or ``geometry``. The model
    registers exactly this list, and the derivative tasks differentiate it, so
    the two cannot drift. ``geometry_constraints`` is what
    ``add_geometry_constraints`` returned on the built geometry component.
    """
    out = [('adj_warmstart.obj_out', 'objective',
            {'scaler': cfg.objective.effective_scaler})]
    lift = cfg.constraints.lift
    if lift.enabled:
        for point in cfg.points:
            if not lift.applies(point.id):
                continue
            kwargs = lift.constraint_kwargs
            if point.target_cl is not None:
                kwargs = {'equals': point.target_cl, 'scaler': lift.scaler}
            out.append((f'{scenario_prefix}{point.id}.C_L', 'lift', kwargs))
    moment = cfg.constraints.moment
    if moment.enabled:
        for point in cfg.points:
            if not moment.applies(point.id):
                continue
            out.append((f'{scenario_prefix}{point.id}.C_M', 'moment',
                        moment.constraint_kwargs))
    for constraint in cfg.constraints.linear:
        out.append((constraint.path, 'linear', constraint.constraint_kwargs))
    for name, kwargs in geometry_constraints:
        out.append((f'{geometry_name}.{name}', 'geometry', kwargs))
    return out


def _shape_dv_options(cfg, n_shape, counts):
    """Return OpenMDAO lower, upper, and scaler for the shape array."""
    shape = cfg.dv.shape
    lower, upper = shape_dv_bounds(shape, cfg.geometry.parameterization, n_shape, counts)
    if cfg.geometry.parameterization == 'hicks_henne' or len(counts) == 1:
        return lower, upper, shape.resolved_scaler
    scalers = np.repeat(np.asarray(shape.resolved_scalers), counts)
    return lower, upper, scalers


class TopOpt(Multipoint):
    """dvs -> mesh -> geometry -> N scenarios -> weighted objective."""

    def initialize(self):
        self.options.declare('cfg', recordable=False,
                             desc='a validated mdao_su2.run_config.RunConfig')
        self.options.declare('point_cfgs', types=list,
                             desc='list of (primal_cfg, adjoint_cfg) per point, '
                                  'as generated by su2.cfggen')

    # ------------------------------------------------------------- setup

    def setup(self):
        cfg = self.options['cfg']
        point_cfgs = self.options['point_cfgs']
        parallel = cfg.execution.parallel_points

        builders = self._make_builders(cfg, point_cfgs)
        self._builders = builders

        if parallel:
            # Separate world-comm builder for metadata; scenario builders init on their sub-comms.
            meta_builder = self._solver_builder(
                cfg, point_cfgs[0][0], point_cfgs[0][1], cfg.points[0])
            meta_builder.initialize(self.comm)
        else:
            for b in builders:
                b.initialize(self.comm)
            meta_builder = builders[0]
        self._meta_builder = meta_builder

        self._alpha0 = [p.aoa_init for p in cfg.points]
        self._scenario_prefix = 'scenarios.' if parallel else ''
        pfx = self._scenario_prefix
        names = cfg.point_ids

        self.add_subsystem('dvs', om.IndepVarComp(), promotes=['*'])

        if parallel:
            # Per-scenario geometry on sub-comms; `geomcon` hosts shared shape DVs + constraints.
            self.add_subsystem('mesh_con',
                               meta_builder.get_mesh_coordinate_subsystem())
            self.add_subsystem('geomcon', build_geometry_component(cfg))
            self.connect(f'mesh_con.{_V.Mesh.COORDINATES}',
                         f'geomcon.{_V.Geometry.COORDINATES_INPUT}')

            def _shape_hook(geometry, builder, _cfg=cfg):
                return add_geometry_dvs(geometry, builder, _cfg)

            scenarios = self.add_subsystem('scenarios', MultipointParallel())
            for name, builder in zip(names, builders):
                scenarios.mphys_add_scenario(
                    name,
                    GeoScenarioAero(aero_builder=builder,
                                    geometry_builder=GeoBuilder(cfg),
                                    in_MultipointParallel=True,
                                    shape_dv_hook=_shape_hook))
        else:
            self.add_subsystem('mesh',
                               meta_builder.get_mesh_coordinate_subsystem())
            self.add_subsystem('geometry', build_geometry_component(cfg))
            self.connect(f'mesh.{_V.Mesh.COORDINATES}',
                         f'geometry.{_V.Geometry.COORDINATES_INPUT}')
            for name, builder in zip(names, builders):
                self.mphys_add_scenario(
                    name, ScenarioAerodynamic(aero_builder=builder))
                self.connect(f'geometry.{_V.Geometry.COORDINATES_OUTPUT}',
                             f'{name}.{_V.COORDINATES}')

        # Objective compiled from [objective] expression; weights enter once, through wsum.
        add_objective_comp(self, cfg.objective_compiled)
        # [[constraints.linear]]: one ExecComp each, fed by the point outputs.
        add_linear_comps(self, cfg.linear_compiled)

        # Adjoint warm start across design iterations; validator forbids under remesh.mode=gmsh.
        self.add_subsystem('adj_warmstart', AdjointWarmStartComp(
            point_cfgs=point_cfgs, enabled=cfg.execution.adjoint_restart))
        self.connect('obj_comb.obj', 'adj_warmstart.obj_in')

    @staticmethod
    def _solver_builder(cfg, primal_cfg, adjoint_cfg, point=None):
        """Select single- or multi-marker builder based on the case's wall marker set."""
        restart = cfg.solver.primal.warm_start
        from ..solver.response_catalog import lookup
        records = tuple(lookup(name) for name in (point.responses if point else ()))
        from dataclasses import replace
        records = tuple(replace(record,
                                su2_objective=cfg.constraints.moment.objective_key,
                                history_field=cfg.constraints.moment.objective_key)
                        if record.name == 'moment' else record for record in records)
        routed_builder, _geometry, _allowed, _reason = derivative_route(cfg, point)
        from ..solver.seam_comp import ResponseSU2Builder
        if routed_builder is ResponseSU2Builder:
            return ResponseSU2Builder(
                primal_cfg, adjoint_cfg,
                wall_markers=cfg.case.design_markers,
                responses=records,
                restart=restart,
                moment_key=cfg.constraints.moment.objective_key,
                adjoint_stall_window=cfg.remesh.solver.adjoint_stall_window,
                adjoint_stall_delta=cfg.remesh.solver.adjoint_stall_delta)
        if routed_builder is not SU2Builder:
            # fwd/auto need forward products. "rev", requested
            # or resolved, uses SU2Builder and its reverse path.
            return routed_builder(primal_cfg, adjoint_cfg,
                                   functionals=cfg.aero_functionals,
                                   wall_marker=cfg.case.wall_single,
                                   restart=restart,
                                   moment_key=cfg.constraints.moment.objective_key)
        return routed_builder(primal_cfg, adjoint_cfg,
                          wall_marker=cfg.case.wall_single, restart=restart,
                          moment_key=cfg.constraints.moment.objective_key)

    def _make_builders(self, cfg, point_cfgs):
        # Fixed mesh + SU2 native warp. No mesh-quality gate.
        # The former remesh branch was unreachable: validation rejects
        # remesh.mode="gmsh", and shipped configs enable no remesh.
        # RemeshConfig remains the shared recipe/schema source for mesh2d.
        return [self._solver_builder(cfg, pcfg, acfg, point)
                for point, (pcfg, acfg) in zip(cfg.points, point_cfgs)]

    # --------------------------------------------------------- configure

    def configure(self):
        cfg = self.options['cfg']
        pfx = self._scenario_prefix
        parallel = cfg.execution.parallel_points
        b = self._meta_builder

        # Shape DVs registered on geomcon (parallel) or geometry (sequential).
        geom_name = 'geomcon' if parallel else 'geometry'
        geom = getattr(self, geom_name)
        # Geometry DVs in cfg.geometry_dvs order: shape, then twist.
        # With neither on the wall is still embedded, so the model runs at a
        # fixed shape (the Case 3 grid study).
        geo_dvs = add_geometry_dvs(geom, b, cfg)
        cons = []
        if cfg.constraints.geometry:
            cons = add_geometry_constraints(geom, b, cfg)

        # [dv] start: unscaled values from a recorded design, checked at load;
        # the shape count and per-DV bounds need the embedded geometry.
        start = read_start(cfg)
        for name in cfg.geometry_dvs:
            n, counts = geo_dvs[name]
            if name == 'shape':
                value = np.zeros(n)
                if start is not None:
                    value = start.values['shape']
                    problems = ([f'{value.size} shape DVs; this geometry has {n}']
                                if value.size != n else check_shape_start(cfg, value, counts))
                    if problems:
                        raise ConfigError(f'[dv] start={start.source!r}: '
                                          + '; '.join(problems))
                self.dvs.add_output('shape', val=value)
                lower, upper, scaler = _shape_dv_options(cfg, n, counts)
            else:
                t = cfg.dv.twist
                value = (start.values[name] if start is not None
                         else np.full(n, t.init_deg))
                self.dvs.add_output(name, val=value)   # DEGREES
                lower, upper, scaler = t.lower_deg, t.upper_deg, t.scaler
            self.add_design_var(name, lower=lower, upper=upper, scaler=scaler)
            # Shared DV -> constraint geometry, fan-out to per-scenario geometries in parallel.
            self.connect(name, f'{geom_name}.{name}')
            if parallel:
                for pid in cfg.point_ids:
                    self.connect(name, f'scenarios.{pid}.geometry.{name}')

        for i, point in enumerate(cfg.points):
            dv = f'alpha_{i}'
            alpha = point.aoa_init
            if start is not None and point.id in start.alphas:
                alpha = start.alphas[point.id][1]
            self.dvs.add_output(dv, val=alpha)   # DEGREES
            self.connect(dv, f'{pfx}{point.id}.alpha')
            if point.alpha == 'design':
                self.add_design_var(dv, lower=point.aoa_lower, upper=point.aoa_upper,
                                    scaler=point.aoa_scaler)

        self.driver_responses = responses(cfg, pfx, geom_name, cons)
        for path, kind, kwargs in self.driver_responses:
            if kind == 'objective':
                self.add_objective(path, **kwargs)
            else:
                self.add_constraint(path, **kwargs)

    # ------------------------------------------------------------ helpers

    @property
    def geometry_name(self):
        """Whichever geometry component carries the constraints and the
        deformed surface -- ``geomcon`` in parallel, ``geometry`` otherwise."""
        return 'geomcon' if self._scenario_prefix else 'geometry'


# --------------------------------------------------------------- assembly

def build_problem(cfg, point_cfgs, comm=None, rundir=None, with_driver=False):
    """Assemble and set up the OpenMDAO problem for ``cfg``."""
    from mpi4py import MPI
    from .optimizer import setup_driver

    prob = om.Problem(comm=comm if comm is not None else MPI.COMM_WORLD)
    prob.model = TopOpt(cfg=cfg, point_cfgs=point_cfgs)
    if with_driver:
        setup_driver(prob, cfg, rundir)
    # A fwd/auto request on a reverse-only configuration resolves to rev, so
    # reverse-only assertions are never reached for a forward-compatible path.
    prob.setup(mode=resolve_derivative_mode(cfg)[1])
    return prob


def gather_coeffs(prob, cfg):
    """Collective gather of per-point C_L, C_D onto EVERY rank. Must be called on all ranks."""
    pfx = prob.model._scenario_prefix
    cls = [float(prob.get_val(f'{pfx}{p.id}.C_L', get_remote=True)[0])
           for p in cfg.points]
    cds = [float(prob.get_val(f'{pfx}{p.id}.C_D', get_remote=True)[0])
           for p in cfg.points]
    return cls, cds
