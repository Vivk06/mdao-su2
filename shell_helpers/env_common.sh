#!/usr/bin/env bash
# Shared helpers for setup.sh, activate.sh, and verify.sh. Source only.

# Disable alias expansion during definition — a `run` alias would break the parse.
# Restored at the end of this file.
_ENV_COMMON_ALIAS_STATE="$(shopt -p expand_aliases 2>/dev/null || true)"
shopt -u expand_aliases 2>/dev/null || true

_ENV_COMMON_LOADED=1

# ── Output helpers ───────────────────────────────────────────────────
die()  { echo "ERROR: $*" >&2; exit 1; }
warn() { echo "WARNING: $*" >&2; }

# run CMD [ARGS…] — execute CMD, or print it under --dry-run.
# Set _DRY_RUN=1 before sourcing to enable dry-run mode.
run() {
    if [ "${_DRY_RUN:-0}" = "1" ]; then
        echo "  [dry-run] $*"
        return 0
    fi
    "$@"
}

# run_in DIR CMD [ARGS…] — pushd DIR, run CMD, popd.
run_in() {
    local dir="$1"; shift
    if [ "${_DRY_RUN:-0}" = "1" ]; then
        echo "  [dry-run] (in $dir) $*"
        return 0
    fi
    pushd "$dir" > /dev/null
    "$@"
    local rc=$?
    popd > /dev/null
    return $rc
}

# parse_env_file FILE — read .env_local into the associative array ENV_FILE_VALUES.
# Handles CRLF, quotes, whitespace, malformed keys. A missing file leaves it empty.
declare -gA ENV_FILE_VALUES=()
parse_env_file() {
    local file="$1" line key val
    ENV_FILE_VALUES=()
    [ -f "$file" ] || return 0
    while IFS= read -r line || [ -n "$line" ]; do
        # Strip CRLF
        line="${line%$'\r'}"
        # Strip leading/trailing whitespace
        line="${line#"${line%%[![:space:]]*}"}"
        line="${line%"${line##*[![:space:]]}"}"
        # Skip comments and blank lines
        [[ "$line" =~ ^#.*$ || -z "$line" ]] && continue
        # Split on first =
        key="${line%%=*}"
        val="${line#*=}"
        # Strip whitespace from key
        key="${key#"${key%%[![:space:]]*}"}"
        key="${key%"${key##*[![:space:]]}"}"
        # Validate key
        if ! [[ "$key" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]]; then
            warn "parse_env_file: skipping malformed key: '$key'"
            continue
        fi
        # Strip matched quotes from value
        val="${val#"${val%%[![:space:]]*}"}"
        val="${val%"${val##*[![:space:]]}"}"
        if [[ "$val" =~ ^\"(.*)\"$ ]]; then
            val="${BASH_REMATCH[1]}"
        elif [[ "$val" =~ ^\'(.*)\'$ ]]; then
            val="${BASH_REMATCH[1]}"
        fi
        ENV_FILE_VALUES[$key]="$val"
    done < "$file"
}

# load_env_file FILE [--file-wins]
# Export FILE's values. By default a variable already set in the environment
# keeps its value (setup.sh: --cli > environment > .env_local). --file-wins
# exports every value from FILE, so activate.sh applies exactly what setup.sh
# resolved even when a shell startup file exports an older prefix.
load_env_file() {
    local file="$1" mode="${2:-}" key
    parse_env_file "$file"
    for key in "${!ENV_FILE_VALUES[@]}"; do
        if [ "$mode" = "--file-wins" ] || [ -z "${!key+x}" ]; then
            export "$key=${ENV_FILE_VALUES[$key]}"
        fi
    done
}

# write_env_file FILE KEY=VAL [KEY=VAL …]
# Atomic write via temp file + mv.
write_env_file() {
    local file="$1"; shift
    local tmp
    tmp="$(mktemp "${file}.XXXXXX")"
    {
        echo "# Auto-generated by setup.sh — do not edit manually, do not commit."
        echo "# Sourced by activate.sh to restore the environment."
        for pair in "$@"; do
            echo "$pair"
        done
    } > "$tmp"
    mv -f "$tmp" "$file"
}

# filter_ld_library_path [KEEP_DIR …]
# Another application's libraries on LD_LIBRARY_PATH replace the system copies
# in every program started from this shell: a bundled OpenSSL looks for CA
# certificates in its own build directory, so wget rejects every HTTPS site, and
# a foreign libmpi or libgfortran breaks MPI runs and scipy. Drops each entry
# that is empty (the loader reads it as the current directory), that holds an
# MPI library, or that holds a library the system linker cache already provides
# from a different file. Entries under a KEEP_DIR stay. Dropped entries and their
# reasons are left in LD_LIBRARY_PATH_DROPPED.
filter_ld_library_path() {
    local -A system_libs=() system_dirs=()
    local ldconfig_bin name path entry keep reason lib same out="" empty_seen=0
    LD_LIBRARY_PATH_DROPPED=()
    [ -n "${LD_LIBRARY_PATH:-}" ] || return 0

    # One name may be cached for several ABIs; keep every path, one per line.
    ldconfig_bin="$(command -v ldconfig 2>/dev/null || echo /sbin/ldconfig)"
    while read -r name path; do
        system_libs[$name]+="$path"$'\n'
        system_dirs[${path%/*}]=1
    done < <("$ldconfig_bin" -p 2>/dev/null | awk 'NR > 1 && $(NF-1) == "=>" {print $1, $NF}')

    while IFS= read -r -d: entry; do
        if [ -z "$entry" ]; then
            [ "$empty_seen" -eq 1 ] || LD_LIBRARY_PATH_DROPPED+=("(empty entry): the loader searches the current directory")
            empty_seen=1
            continue
        fi
        reason=""
        for keep in "$@"; do
            [ -n "$keep" ] || continue
            case "$entry" in "$keep"|"$keep"/*) reason="keep"; break ;; esac
        done
        # Directories the loader already searches cannot replace anything.
        [ -n "${system_dirs[$entry]:-}" ] && reason="keep"
        if [ -z "$reason" ] && [ -d "$entry" ]; then
            for lib in "$entry"/lib*.so*; do
                [ -e "$lib" ] || continue
                name="${lib##*/}"
                case "$name" in
                    libmpi.so*|libmpi_*.so*|libopen-pal.so*|libpmix.so*)
                        reason="holds another MPI ($name)"; break ;;
                    libssl.so*|libcrypto.so*|libgfortran.so*|libgcc_s.so*|libstdc++.so*) ;;
                    *) [ -n "${system_libs[$name]:-}" ] || continue ;;
                esac
                same=0
                while IFS= read -r path; do
                    [ -n "$path" ] && [ "$lib" -ef "$path" ] && { same=1; break; }
                done <<< "${system_libs[$name]:-}"
                if [ "$same" -eq 0 ]; then
                    reason="$name replaces the system copy"; break
                fi
            done
        fi
        if [ -n "$reason" ] && [ "$reason" != "keep" ]; then
            LD_LIBRARY_PATH_DROPPED+=("$entry: $reason")
            continue
        fi
        out="${out:+$out:}$entry"
    done < <(printf '%s:' "$LD_LIBRARY_PATH")
    export LD_LIBRARY_PATH="$out"
}

# filter_python_path [KEEP_ENTRY …]
# PYTHONPATH entries come before the venv's site-packages on sys.path, so an
# entry another application exports from a shell startup file (e.g. a Python 2.7
# site-packages) replaces the venv's scipy, numpy, setuptools or mpi4py, and the
# venv's own import check still passes because it runs without that entry.
# Keeps only entries equal to a KEEP_ENTRY and unsets PYTHONHOME, which points
# the interpreter at another installation's standard library. Sets
# PYTHON_PATH_DROPPED to the number of entries (and PYTHONHOME) removed.
filter_python_path() {
    local entry keep kept out=""
    PYTHON_PATH_DROPPED=0
    if [ -n "${PYTHONHOME+x}" ]; then
        [ -z "$PYTHONHOME" ] || PYTHON_PATH_DROPPED=$(( PYTHON_PATH_DROPPED + 1 ))
        unset PYTHONHOME
    fi
    if [ -n "${PYTHONPATH:-}" ]; then
        while IFS= read -r -d: entry; do
            [ -n "$entry" ] || continue
            kept=0
            for keep in "$@"; do
                [ "$entry" = "$keep" ] && { kept=1; break; }
            done
            if [ "$kept" -eq 1 ]; then
                out="${out:+$out:}$entry"
            else
                PYTHON_PATH_DROPPED=$(( PYTHON_PATH_DROPPED + 1 ))
            fi
        done < <(printf '%s:' "$PYTHONPATH")
    fi
    if [ -n "$out" ]; then export PYTHONPATH="$out"; else unset PYTHONPATH; fi
}

# drop_python_shims — remove python/pip aliases and shell functions. A ~/.bashrc
# alias such as python=python2.7 runs instead of the venv's interpreter whatever
# PATH says. Sets PYTHON_SHIMS_DROPPED to the number removed.
drop_python_shims() {
    local name
    PYTHON_SHIMS_DROPPED=0
    for name in python python3 python3.14 pip pip3 pip3.14; do
        case "$(type -t "$name" 2>/dev/null)" in
            alias)    unalias "$name"; PYTHON_SHIMS_DROPPED=$(( PYTHON_SHIMS_DROPPED + 1 )) ;;
            function) unset -f "$name"; PYTHON_SHIMS_DROPPED=$(( PYTHON_SHIMS_DROPPED + 1 )) ;;
        esac
    done
}

# Restore the caller's alias-expansion setting (see the top of this file).
eval "$_ENV_COMMON_ALIAS_STATE"
unset _ENV_COMMON_ALIAS_STATE
